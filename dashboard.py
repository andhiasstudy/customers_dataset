import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import streamlit as st
from babel.numbers import format_currency
sns.set(style='dark')


customer_df = pd.read_csv("C:/Users/LENOVO/Downloads/dashboard_project/customers_dataset.csv")

# ======================
# Header
# ======================
st.title("Customer Analysis Dashboard")
st.markdown("Analisis pelanggan berdasarkan kota dan state")

# ======================
# Sidebar Filter
# ======================
with st.sidebar:
    st.header("Filter Data")

    state_option = st.multiselect(
        "Pilih State",
        options=customer_df["customer_state"].unique(),
        default=customer_df["customer_state"].unique()
    )

# Filter data
main_df = customer_df[customer_df["customer_state"].isin(state_option)]

# ======================
# METRIC
# ======================
st.subheader("Ringkasan Data")

col1, col2 = st.columns(2)

with col1:
    total_customer = main_df["customer_unique_id"].nunique()
    st.metric("Total Customer Unik", total_customer)

with col2:
    total_city = main_df["customer_city"].nunique()
    st.metric("Total Kota", total_city)

# ======================
# TOP KOTA
# ======================
st.subheader("Top 10 Kota dengan Pelanggan Terbanyak")

top_city = (
    main_df.groupby("customer_city")["customer_unique_id"]
    .nunique()
    .sort_values(ascending=False)
    .head(10)
    .reset_index()
)

fig, ax = plt.subplots(figsize=(10,5))
sns.barplot(data=top_city, x="customer_unique_id", y="customer_city", ax=ax)
ax.set_xlabel("Jumlah Pelanggan")
ax.set_ylabel("Kota")

st.pyplot(fig)

# ======================
# DISTRIBUSI STATE
# ======================
st.subheader("Distribusi Pelanggan per State")

state_dist = (
    main_df.groupby("customer_state")["customer_unique_id"]
    .nunique()
    .reset_index(name="jumlah_pelanggan")
    .sort_values(by="jumlah_pelanggan", ascending=False)
)

fig, ax = plt.subplots(figsize=(10,5))
sns.barplot(data=state_dist, x="customer_state", y="jumlah_pelanggan", ax=ax)

plt.xticks(rotation=45)
st.pyplot(fig)

# ======================
# RAW DATA
# ======================
st.subheader("Data Mentah")
st.dataframe(main_df)

